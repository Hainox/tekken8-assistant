def all_terms() -> list[tuple[str, str, str]]:
    return [
        (category, term, desc)
        for category, terms in GLOSSARY.items()
        for term, desc in terms
    ]


def lookup(term: str) -> str | None:
    key = term.strip().upper()
    for _category, t, desc in all_terms():
        if t.upper() == key:
            return desc
    return None
